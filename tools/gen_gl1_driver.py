#!/usr/bin/env python3
"""Generate the Android GLES 1.1 driver passthrough from the portable seam.

core/include/zb/gl1_backend.h declares one virtual per GLES 1.1-only entry point, with a default
body that records the call through invoke() so a host mock only implements one function. The real
driver backend must not go through that path: it has to call the actual ::gl* entry point of
libGLESv1_CM.so, which is faster and keeps the driver's own error state correct. Writing 87
forwarders by hand invites a silent typo (a wrong parameter order compiles and renders garbage),
so they are generated from the seam and checked by a ctest.

GLES 1.1 has no return value and no 64-bit parameter: every function is `void gl*` and every
argument is a scalar word or a pointer. That makes the translation purely mechanical.

    tools/gen_gl1_driver.py            rewrite the committed .inc files
    tools/gen_gl1_driver.py --check    fail if a committed file is stale
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SEAM = ROOT / "core" / "include" / "zb" / "gl1_backend.h"
HOSTCALLS = ROOT / "core" / "include" / "zb" / "gles1_hostcalls.h"
DECLARATIONS = ROOT / "core" / "android" / "gl1_driver_backend_overrides.inc"
BODIES = ROOT / "core" / "android" / "gl1_driver_backend_bodies.inc"

EXPECTED_FUNCTIONS = 87

SIGNATURE = re.compile(r"^    virtual void (\w+)\((.*)\) \{$")
HOSTCALL_INDEX = re.compile(r"inline constexpr std::uint32_t ZB_GL1_HC_(\w+) = (\d+)u;")


def seam_functions() -> list[tuple[str, str]]:
    """(name, argument list) for every virtual in the seam, in declaration order."""
    functions: list[tuple[str, str]] = []
    for line in SEAM.read_text(encoding="ascii").splitlines():
        match = SIGNATURE.match(line)
        if match:
            functions.append((match.group(1), match.group(2).strip()))
    return functions


def hostcall_names() -> list[str]:
    """The dispatch table's names ordered by index, to prove the seam matches the table."""
    indexed: list[tuple[int, str]] = []
    for line in HOSTCALLS.read_text(encoding="ascii").splitlines():
        match = HOSTCALL_INDEX.search(line)
        if match:
            indexed.append((int(match.group(2)), match.group(1)))
    indexed.sort()
    return [name for _, name in indexed]


def parameter_names(arguments: str) -> list[str]:
    """The trailing identifier of each parameter, with the pointer star attached to the type."""
    if arguments == "void":
        # The seam writes an explicit empty parameter list the C way; C++ accepts it, but it
        # names nothing to forward.
        return []
    names: list[str] = []
    for argument in arguments.split(","):
        argument = argument.strip()
        if not argument:
            continue
        # "const GLfloat *eqn" and "GLenum func" both end in the name after a space.
        names.append(argument.rsplit(" ", 1)[-1].lstrip("*"))
    return names


def generate() -> tuple[str, str]:
    functions = seam_functions()
    if len(functions) != EXPECTED_FUNCTIONS:
        sys.exit(f"{SEAM}: {len(functions)} virtuals, expected {EXPECTED_FUNCTIONS}")
    names = [name for name, _ in functions]
    table = hostcall_names()
    if names != table:
        missing = sorted(set(table) - set(names))
        extra = sorted(set(names) - set(table))
        sys.exit(f"seam and host-call table disagree: missing={missing} extra={extra}")
    if len(set(names)) != len(names):
        sys.exit("the seam declares a name twice")

    declarations = [
        "// Generated by tools/gen_gl1_driver.py from core/include/zb/gl1_backend.h. Do not edit.",
        "",
    ]
    bodies = [
        "// Generated by tools/gen_gl1_driver.py from core/include/zb/gl1_backend.h. Do not edit.",
        "",
    ]
    for name, arguments in functions:
        declarations.append(f"    void {name}({arguments}) override;")
        call_arguments = ", ".join(parameter_names(arguments))
        bodies.append(f"void Gl1DriverBackend::{name}({arguments}) {{")
        bodies.append(f"    ::{name}({call_arguments});")
        bodies.append("}")
        bodies.append("")
    return "\n".join(declarations) + "\n", "\n".join(bodies) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="fail instead of writing when a committed file is stale")
    args = parser.parse_args()

    declarations, bodies = generate()
    stale = False
    for path, text in ((DECLARATIONS, declarations), (BODIES, bodies)):
        if args.check:
            current = path.read_text(encoding="ascii") if path.exists() else ""
            if current != text:
                print(f"{path.relative_to(ROOT)} is stale; run tools/gen_gl1_driver.py",
                      file=sys.stderr)
                stale = True
        else:
            path.write_text(text, encoding="ascii", newline="\n")
            print(f"wrote {path.relative_to(ROOT)}")
    return 1 if stale else 0


if __name__ == "__main__":
    raise SystemExit(main())
